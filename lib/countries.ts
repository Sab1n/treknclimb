/**
 * `as const` freezes the array into a tuple of string literals, and
 * `(typeof COUNTRIES)[number]` reads the union of its members back out. So
 * `Country` is a type meaning "one of exactly these 242 strings" — the list is
 * written once and serves as both the runtime data for the select and the
 * compile-time type, with no way for the two to drift.
 */
export type Country = (typeof COUNTRIES)[number];

/** Fast membership check for the validator. Built once, not per submission. */
const COUNTRY_SET: ReadonlySet<string> = new Set(COUNTRIES);

export function isCountry(value: string): value is Country {
  return COUNTRY_SET.has(value);
}
