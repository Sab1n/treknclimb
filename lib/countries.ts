/**
 * The country list behind the nationality field on the inquiry form.
 *
 * **Nationality is a deliberate amendment to SRS §11, not prototype drift.**
 * Nepal's permit fees and visa requirements differ by nationality — SAARC
 * nationals pay different trekking permit rates, and the on-arrival visa rules
 * are not the same for every passport — so a quote cannot be accurate without
 * it. It is required for that reason.
 *
 * ## Why a fixed list rather than free text
 *
 * The value is stored and has to stay filterable: "how many inquiries from
 * Germany this season" must be one query, not a fuzzy match over "Germany",
 * "germany", "DE", "German" and "Deutschland". A closed list makes that
 * structural rather than a data-cleaning job later.
 *
 * ## Names, not codes
 *
 * The stored value is the country name, by decision. It reads correctly in the
 * admin list, in the notification email and in an export with nothing to join
 * against. The cost is that a country renaming is a data migration rather than
 * a label change — the list below is versioned in code, so that migration is at
 * least findable.
 *
 * Generated once from `Intl.DisplayNames` over the ISO 3166-1 alpha-2 set and
 * then frozen here as literals, deliberately: deriving the names at runtime
 * would let an ICU update silently change values we have already stored.
 * Uninhabited territories (Antarctica, Bouvet Island, the outlying islands)
 * are dropped — nobody holds that nationality — and the two Congos and Myanmar
 * use their conventional English names rather than the CLDR forms.
 *
 * The client may want to amend this list. It is one array, in one file.
 */
